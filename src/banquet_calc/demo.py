def _write(path: Path, sheets: dict[str, pd.DataFrame]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with pd.ExcelWriter(path, engine="openpyxl") as writer:
        for name, frame in sheets.items():
            frame.to_excel(writer, sheet_name=name, index=False)
            writer.sheets[name].column_dimensions["A"].width = 34
            writer.sheets[name].column_dimensions["C"].width = 34
    return path


def build_demo(folder: Path) -> tuple[Path, Path]:
    """Возвращает (меню, номенклатура)."""
    catalog = _write(
        folder / "номенклатура.xlsx",
        {
            "Разделы": pd.DataFrame(SECTIONS, columns=["Раздел", "Название в закупке", "Порядок"]),
            "Продукты": pd.DataFrame(PRODUCTS, columns=PRODUCT_HEADER),
        },
    )
    menu = _write(
        folder / "банкет на 40 гостей.xlsx",
        {
            "Меню": pd.DataFrame(MENU, columns=["Блюдо", "Порций"]),
            "Техкарты": pd.DataFrame(
                TECHCARDS, columns=["Техкарта", "Тип", "Ингредиент", "Количество", "Коэф. отхода"]
            ),
            "Своя номенклатура": pd.DataFrame(
                [("Сырная тарелка от партнёра", "молочные", "шт", 1, 1800, "«Сырная лавка»", "")],
                columns=PRODUCT_HEADER,
            ),
            "Параметры": pd.DataFrame([("Запас, %", 5)], columns=["Параметр", "Значение"]),
        },
    )
    return menu, catalog


